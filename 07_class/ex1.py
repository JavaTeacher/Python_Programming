#
#  2) (  )
#  - 클래스(설계도)로 만들어진 (  ) (예: 붕어빵, 자동차)
#  - 하나의 클래스로 객체를 여러 개 만들 수 있음 (객체는 서로 독립적임)
#
#  3) (  ): 객체가 가진 (  ) (예: 이름, 나이, 키)
#
#  4) (  ): 객체가 할 수 있는 (  ) (예: 먹기, 공부하기)
