#  1. (  ) 프로그래밍 (OOP, Object Oriented Programming)
#  : 관련된 (  )와 (  )을 (  )라는 독립된 단위로 묶어
#    이들의 상호작용으로 프로그램을 구성하는 프로그래밍 패러다임
